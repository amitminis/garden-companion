  var DICTS = {he: HE};
  var lang = "he";
  try { lang = localStorage.getItem("gc.lang") === "en" ? "en" : "he"; } catch(e){}

  function applyDir(){
    var root = document.documentElement;
    root.lang = lang;
    root.dir = lang === "he" ? "rtl" : "ltr";
  }
  function setLang(l){
    lang = l === "en" ? "en" : "he";
    try { localStorage.setItem("gc.lang", lang); } catch(e){}
    applyDir();
  }
  function fill(s, vars){
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, function(m, k){ return Object.prototype.hasOwnProperty.call(vars, k) ? vars[k] : m; });
  }
  // t("Save") -> "שמירה"; t("Using {place}.", {place:"Modi'in"}).
  function t(s, vars){
    var d = DICTS[lang];
    return fill(d && Object.prototype.hasOwnProperty.call(d, s) ? d[s] : s, vars);
  }
  // Plural: tn(3, "1 plant", "{n} plants") -> "3 צמחים"; uses the "#2"
  // (dual) entry for n = 2 where the language has one.
  function tn(n, one, many, vars){
    vars = Object.assign({n:n}, vars || {});
    var d = DICTS[lang];
    if (n === 2 && d && Object.prototype.hasOwnProperty.call(d, many + "#2")) return fill(d[many + "#2"], vars);
    return t(n === 1 ? one : many, vars);
  }

  window.I18N = {
    t: t, tn: tn, setLang: setLang,
    lang: function(){ return lang; },
    isRTL: function(){ return lang === "he"; },
    // For toLocaleDateString(); undefined = the browser's own English locale.
    locale: function(){ return lang === "he" ? "he-IL" : undefined; },
    _dict: HE
  };
  applyDir();
